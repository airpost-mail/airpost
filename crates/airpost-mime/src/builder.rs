//! Outgoing messages for SendDraft and EventRSVP.
//!
//! Derived from mailcore2 `MessageBuilder::mimeAndFilterBccAndForEncryption` and
//! `MessageHeader::createIMFFieldsAndFilterBcc` (Copyright © 2001-2013 MailCore team,
//! BSD-3-Clause) and from Mailspring-Sync `TaskProcessor::performRemoteSendDraft` /
//! `performRemoteEventRSVP` (`TaskProcessor.cpp:2125-2215, 3062-3130`, Copyright © 2017
//! Foundry 376, GPL-3.0). See NOTICE.md ("mailcore2").
//!
//! Structure, as mailcore builds it:
//! - HTML: `multipart/alternative` of the flattened text and the HTML; files with a
//!   Content-ID go with the HTML in `multipart/related`.
//! - Plain text: a single `text/plain` part.
//! - Calendar (RSVP, RFC 6047 section 2.4): `multipart/alternative` of a `text/plain`
//!   summary and `text/calendar; method=…`, both base64, the calendar inline.
//! - Files without a Content-ID: `multipart/mixed` around all of the above.
//!
//! The Bcc field stays in [`build`]'s output, which is the copy appended to Sent; the SMTP
//! layer strips it from the wire copy (`tern_smtp::message::filter_bcc`).

use mail_builder::encoders::Base64Encoder;
use mail_builder::headers::address::Address as MbAddress;
use mail_builder::headers::content_type::ContentType;
use mail_builder::headers::date::Date;
use mail_builder::headers::message_id::MessageId;
use mail_builder::headers::raw::Raw;
use mail_builder::headers::text::Text;
use mail_builder::mime::{BodyPart, MimePart};
use mail_builder::MessageBuilder;
use tern_core::{Address, Error, Result};

use crate::files::mime_type_for_filename;
use crate::flatten::flatten_html_with;

/// The `X-Mailer` value (`setUserAgent`).
pub const USER_AGENT: &str = "Tern";

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct OutgoingAttachment {
    /// The name in Content-Disposition. The C++ sent the on-disk name, which is the
    /// File's `safeFilename`.
    pub filename: String,
    /// Empty: derived from the filename's extension, as mailcore did.
    pub mime_type: String,
    /// Set for inline images referenced as `cid:`; those go under `multipart/related`.
    pub content_id: Option<String>,
    pub data: Vec<u8>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum OutgoingBody {
    /// An HTML draft; a text alternative is generated by flattening.
    Html(String),
    /// A plaintext draft (`draft.plaintext`).
    Text(String),
    /// An iTIP reply or counter-proposal: a human-readable summary and the ICS.
    Calendar {
        text: String,
        /// The iTIP method (`REPLY`, `COUNTER`), which must match the ICS's METHOD.
        method: String,
        ics: String,
    },
}

impl Default for OutgoingBody {
    fn default() -> Self {
        OutgoingBody::Html(String::new())
    }
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct OutgoingMessage {
    /// Only the first address is written (`setFrom(draft.from().at(0))`).
    pub from: Vec<Address>,
    pub to: Vec<Address>,
    pub cc: Vec<Address>,
    pub bcc: Vec<Address>,
    pub reply_to: Vec<Address>,
    pub subject: String,
    /// Without angle brackets. Empty: a `uuid@hostname` id is generated, as mailcore's
    /// `MessageHeader` did.
    pub message_id: String,
    /// Epoch seconds for the Date header.
    pub date: i64,
    /// `replyToHeaderMessageId`: sets In-Reply-To and References.
    pub in_reply_to: Option<String>,
    /// `forwardedHeaderMessageId`: sets References only, replacing the reply's.
    pub forwarded_message_id: Option<String>,
    pub body: OutgoingBody,
    /// `hImportance`: `high` or `low` add Importance, X-Priority and X-MSMail-Priority.
    pub importance: Option<String>,
    /// The X-Mailer value; empty means [`USER_AGENT`].
    pub user_agent: String,
    /// Written after the standard fields, in order.
    pub extra_headers: Vec<(String, String)>,
    pub attachments: Vec<OutgoingAttachment>,
}

/// Renders the message as RFC 5322 bytes, Bcc included (`MessageBuilder::data`).
pub fn build(msg: &OutgoingMessage) -> Result<Vec<u8>> {
    build_filtering_bcc(msg, false)
}

/// `dataAndFilterBccAndForEncryption(filterBcc, false)`.
pub fn build_filtering_bcc(msg: &OutgoingMessage, filter_bcc: bool) -> Result<Vec<u8>> {
    let mut b = MessageBuilder::new();
    b = b.date(Date::new(msg.date));
    if let Some(from) = msg.from.first() {
        b = b.from(address(from));
    }
    if !msg.reply_to.is_empty() {
        b = b.reply_to(address_list(&msg.reply_to));
    }
    if !msg.to.is_empty() {
        b = b.to(address_list(&msg.to));
    }
    if !msg.cc.is_empty() {
        b = b.cc(address_list(&msg.cc));
    }
    if !filter_bcc && !msg.bcc.is_empty() {
        b = b.bcc(address_list(&msg.bcc));
    }
    let message_id = if msg.message_id.trim().is_empty() {
        generated_message_id()
    } else {
        tern_core::ids::strip_angle_brackets(&msg.message_id).to_owned()
    };
    b = b.message_id(MessageId::new(message_id));

    let reply = msg
        .in_reply_to
        .as_deref()
        .map(clean_id)
        .filter(|s| !s.is_empty());
    let forwarded = msg
        .forwarded_message_id
        .as_deref()
        .map(clean_id)
        .filter(|s| !s.is_empty());
    if let Some(r) = &reply {
        b = b.in_reply_to(MessageId::new(r.clone()));
    }
    if let Some(refs) = forwarded.as_ref().or(reply.as_ref()) {
        b = b.references(MessageId::new(refs.clone()));
    }
    if !msg.subject.is_empty() {
        b = b.subject(Text::new(msg.subject.clone()));
    }

    let user_agent = if msg.user_agent.is_empty() {
        USER_AGENT
    } else {
        msg.user_agent.as_str()
    };
    b = b.header("X-Mailer", Text::new(user_agent.to_owned()));
    for (name, value) in priority_headers(msg.importance.as_deref()) {
        b = b.header(name, Raw::new(value));
    }
    for (name, value) in &msg.extra_headers {
        b = b.header(name.clone(), Text::new(value.clone()));
    }

    b = b.body(body_tree(msg));
    b.write_to_vec()
        .map_err(|e| Error::Other(format!("MessageBuilder: {e}")))
}

/// The priority headers for `hImportance` (`TaskProcessor.cpp:2186-2198`).
fn priority_headers(importance: Option<&str>) -> Vec<(&'static str, &'static str)> {
    match importance {
        Some("high") => vec![
            ("Importance", "high"),
            ("X-Priority", "1 (Highest)"),
            ("X-MSMail-Priority", "High"),
        ],
        Some("low") => vec![
            ("Importance", "low"),
            ("X-Priority", "5 (Lowest)"),
            ("X-MSMail-Priority", "Low"),
        ],
        _ => Vec::new(),
    }
}

fn clean_id(id: &str) -> String {
    tern_core::ids::strip_angle_brackets(id).to_owned()
}

fn generated_message_id() -> String {
    let host = hostname::get()
        .ok()
        .and_then(|h| h.into_string().ok())
        .filter(|h| !h.is_empty())
        .unwrap_or_else(|| "localhost".to_owned());
    format!("{}@{host}", uuid::Uuid::new_v4().to_string().to_uppercase())
}

fn address(a: &Address) -> MbAddress<'static> {
    let name = a.name.clone().filter(|n| !n.is_empty());
    MbAddress::new_address(name, a.email.clone())
}

fn address_list(list: &[Address]) -> MbAddress<'static> {
    MbAddress::new_list(list.iter().map(address).collect())
}

fn body_tree(msg: &OutgoingMessage) -> MimePart<'static> {
    let (related, files): (Vec<&OutgoingAttachment>, Vec<&OutgoingAttachment>) =
        msg.attachments.iter().partition(|a| a.content_id.is_some());

    let (main, leftover_related) = match &msg.body {
        OutgoingBody::Html(html) => {
            let html_part = text_part("text/html", html.clone());
            let html_part = if related.is_empty() {
                html_part
            } else {
                let mut parts = vec![html_part];
                parts.extend(related.iter().map(|a| file_part(a, true)));
                MimePart::new("multipart/related", parts)
            };
            let text = text_part("text/plain", flatten_html_with(html, true, true));
            (
                MimePart::new("multipart/alternative", vec![text, html_part]),
                Vec::new(),
            )
        }
        // mailcore only placed related files next to an HTML body; with any other body
        // they are attached normally rather than dropped.
        OutgoingBody::Text(text) => (text_part("text/plain", text.clone()), related),
        OutgoingBody::Calendar { text, method, ics } => {
            let summary = MimePart::new(
                ContentType::new("text/plain").attribute("charset", "UTF-8"),
                BodyPart::Binary(base64(text.as_bytes()).into()),
            )
            .transfer_encoding("base64");
            let calendar = MimePart::new(
                ContentType::new("text/calendar")
                    .attribute("method", method.clone())
                    .attribute("charset", "UTF-8"),
                BodyPart::Binary(base64(ics.as_bytes()).into()),
            )
            .header(
                "Content-Disposition",
                ContentType::new("inline").attribute("filename", "invite.ics"),
            )
            .transfer_encoding("base64");
            (
                MimePart::new("multipart/alternative", vec![summary, calendar]),
                related,
            )
        }
    };

    let mut mixed: Vec<MimePart<'static>> = leftover_related
        .iter()
        .chain(files.iter())
        .map(|a| file_part(a, false))
        .collect();
    if mixed.is_empty() {
        return main;
    }
    mixed.insert(0, main);
    MimePart::new("multipart/mixed", mixed)
}

/// `get_plain_text_part` / `get_other_text_part`: UTF-8, `Content-Disposition: inline`.
fn text_part(mime: &'static str, text: String) -> MimePart<'static> {
    MimePart::new(
        ContentType::new(mime).attribute("charset", "utf-8"),
        BodyPart::Text(text.into()),
    )
    .inline()
}

/// `get_file_part`: base64, the filename in Content-Disposition, inline for related files.
fn file_part(a: &OutgoingAttachment, inline: bool) -> MimePart<'static> {
    let mut mime = if a.mime_type.trim().is_empty() {
        mime_type_for_filename(&a.filename).to_owned()
    } else {
        a.mime_type.trim().to_ascii_lowercase()
    };
    // RFC 2046 5.2.1 and 5.1: message/* and multipart/* bodies may not be base64 encoded.
    // mailcore re-parsed message/rfc822 data and embedded it raw, which is only valid for
    // 7bit/8bit content; sending such files as octet-stream (what the C++ did off macOS)
    // keeps the bytes intact.
    if mime.starts_with("message/") || mime.starts_with("multipart/") {
        mime = "application/octet-stream".to_owned();
    }
    let disposition = ContentType::new(if inline { "inline" } else { "attachment" })
        .attribute("filename", a.filename.clone());
    let mut part = MimePart::new(
        ContentType::new(mime),
        BodyPart::Binary(base64(&a.data).into()),
    )
    .transfer_encoding("base64");
    if let Some(cid) = &a.content_id {
        part = part.cid(clean_id(cid));
    }
    part.header("Content-Disposition", disposition)
}

fn base64(data: &[u8]) -> Vec<u8> {
    Base64Encoder::new()
        .wrap_lines()
        .encode(data)
        .unwrap_or_default()
}
